export function getCuratedVocabularyExample(level, word) {
  const words = level === 'elementary' ? ELEMENTARY : level === 'junior' ? JUNIOR : null;
  const key=String(word || '').trim().toLowerCase();
  const pair = words?.[key];
  const meanings=level==='junior'?{flour:'麵粉；磨成的粉末',instant:'立即的；即食的',tight:'緊的；緊湊的',withdraw:'撤回；提領'}:{};
  return Array.isArray(pair) ? { ex: pair[0], ez: pair[1], ...(meanings[key]?{m:meanings[key]}:{}) } : null;
}

