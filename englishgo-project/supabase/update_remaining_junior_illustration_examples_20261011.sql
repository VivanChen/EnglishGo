  UPDATE public.word_bank AS w
  SET example = c.example,
      example_zh = c.example_zh
  FROM corrections AS c
  WHERE w.level = 'junior'
    AND w.word = c.word
  RETURNING w.word, w.example, w.example_zh
),
updated_illustrations AS (
  UPDATE public.word_illustrations AS i
  SET example = u.example,
      example_zh = u.example_zh
  FROM updated_bank AS u
  WHERE i.level = 'junior'
    AND i.word = u.word
  RETURNING i.word
)
